// Ставить ціни послуг: типові ціни ринку Києва (звіт «Ціни подолога Київ 2026», прайси перевірені 23.11.2026).
// Це ринкові орієнтири, не власні ціни кабінету — власник може змінити будь-яку у вкладці «Послуги».
// Послуги шукаються за точною назвою. Поле «Орієнтовна ціна (текст)» не чіпається:
// якщо воно заповнене, на сайті показується саме воно.
//
// Перегляд без змін:  node scripts/set-prices.js
// Записати в базу:    node scripts/set-prices.js --apply
const path = require('path');
const Database = require('better-sqlite3');

// 0 — даних про ціну немає, на сайті буде «ціна уточнюється»
const PRICES = {
  'Первинний огляд стоп': 650, // 2 прайси: 600–700, середина
  'Медичний педикюр': 1400,
  'Корекція врослого нігтя скобою або пластиною': 1350,
  'Консультація подолога': 500,
  'Обробка врослого нігтя': 600,
  'Обробка потовщених нігтів': 800,
  'Обробка нігтів, уражених грибком': 550,
  'Видалення мозолів і натоптишів': 530, // типова 525, округлено до 10
  'Видалення стрижневої мозолі': 700, // 2 прайси: 350–1000, середина ≈ 675
  "Обробка тріщин на п'ятах": 1000, // 3 прайси: 300–1700, середина
  'Видалення бородавок': 700,
  'Протезування нігтьової пластини': 700, // 2 прайси: 480–960, середина ≈ 720
  'Педикюр при цукровому діабеті': 1700,
  'Індивідуальні силіконові ортези': 540, // 1 прайс
  'Тейпування стопи': 100, // 1 прайс, «від 100»
  'Повторний огляд, заміна або зняття скоби': 500, // повторний огляд 500; заміна скоби ~1000, зняття ~280
  'Дитячий подологічний прийом': 500, // 1 прайс, «від 500»
  'Тампонада врослого нігтя': 250,
  'Встановлення титанової нитки': 1450,
  'Корекція закрученого нігтя': 0, // немає даних
  'Обробка нігтя при оніхолізисі': 1050, // 2 прайси: 400–1700, середина
  'Чоловічий подологічний педикюр': 1600, // 1 прайс
  'Педикюр для людей похилого віку': 0, // немає даних
  'Педикюр з покриттям гель-лаком': 1650, // 1 прайс
  "Комп'ютерна діагностика стоп": 1900, // 2 прайси, обидва не зовсім ця послуга
  'Парафінотерапія для стоп': 0, // немає даних
};

const apply = process.argv.includes('--apply');
const dbPath = process.env.DB_PATH || path.join(__dirname, '..', 'data', 'studio.db');
const db = new Database(dbPath, { readonly: !apply });

const rows = db.prepare('SELECT id, name, price_uah, price_note FROM services').all();
const byName = new Map(rows.map((r) => [r.name.trim(), r]));
const upd = apply ? db.prepare('UPDATE services SET price_uah = ? WHERE id = ?') : null;

let changed = 0;
const missing = [];
const run = () => {
  for (const [name, price] of Object.entries(PRICES)) {
    const r = byName.get(name);
    if (!r) { missing.push(name); continue; }
    const note = r.price_note ? `  (на сайті показується текст «${r.price_note}»)` : '';
    if (r.price_uah === price) { console.log(`  без змін  ${name}: ${price} грн${note}`); continue; }
    console.log(`  ${r.price_uah} → ${price} грн  ${name}${note}`);
    if (upd) upd.run(price, r.id);
    changed++;
  }
};
apply ? db.transaction(run)() : run();

const unknown = rows.filter((r) => !(r.name.trim() in PRICES)).map((r) => r.name);
if (missing.length) console.log('\nНемає в базі (назву змінено?):\n  ' + missing.join('\n  '));
if (unknown.length) console.log('\nПослуги без ринкової ціни в скрипті (не змінено):\n  ' + unknown.join('\n  '));
console.log(`\n${apply ? 'Змінено' : 'Буде змінено'}: ${changed}.` + (apply ? '' : ' Щоб записати, запусти з --apply.'));
